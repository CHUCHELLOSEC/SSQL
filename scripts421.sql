-- ------------------------------------------------------------
-- ОГРАНИЧЕНИЕ 1: возраст студента не может быть меньше 16
-- Используем CHECK
-- ------------------------------------------------------------
ALTER TABLE student
    ADD CONSTRAINT chk_student_age_min CHECK (age >= 16);

-- ------------------------------------------------------------
-- ОГРАНИЧЕНИЕ 2: имя студента уникально и не равно NULL
-- UNIQUE + NOT NULL (в PostgreSQL достаточно UNIQUE,
-- но NOT NULL тоже явно укажем)
-- ------------------------------------------------------------
ALTER TABLE student
    ALTER COLUMN name SET NOT NULL;

ALTER TABLE student
    ADD CONSTRAINT uq_student_name UNIQUE (name);

-- ------------------------------------------------------------
-- ОГРАНИЧЕНИЕ 3: пара (название факультета, цвет) уникальна
-- Составной UNIQUE
-- ------------------------------------------------------------
ALTER TABLE faculty
    ADD CONSTRAINT uq_faculty_name_color UNIQUE (name, color);

-- ------------------------------------------------------------
-- ОГРАНИЧЕНИЕ 4: возраст по умолчанию = 20
-- ------------------------------------------------------------
