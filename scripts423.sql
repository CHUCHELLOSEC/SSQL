-- ------------------------------------------------------------
-- ЗАПРОС 1: все студенты с названиями их факультетов
-- Используем LEFT JOIN, чтобы включить студентов без факультета
-- ------------------------------------------------------------
SELECT s.name    AS student_name,
       s.age     AS student_age,
       f.name    AS faculty_name
FROM student s
         LEFT JOIN faculty f ON s.faculty_id = f.id;

-- ------------------------------------------------------------
-- ЗАПРОС 2: только студенты, у которых есть аватарки
-- Используем INNER JOIN — нам нужны только совпадения
-- ------------------------------------------------------------
SELECT s.name AS student_name,
       a.file_path AS avatar_path,
       a.media_type AS avatar_type
FROM student s
         INNER JOIN avatar a ON a.student_id = s.id;